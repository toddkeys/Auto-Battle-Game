"""Builds ro-autobattler.html from tools/game_template.html + assets/units/*.png.
Run after build_sprites.py:  python tools/build_game.py"""
import base64
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
tpl = open(os.path.join(HERE, 'game_template.html'), encoding='utf8').read()

data = {}
for cid in re.findall(r"\{id:'(\w+)'", tpl):
    with open(os.path.join(ROOT, 'assets', 'units', cid + '.png'), 'rb') as f:
        # every generated sprite looks down-left
        data[cid] = {'src': 'data:image/png;base64,' + base64.b64encode(f.read()).decode(), 'faceLeft': True}
    rig = os.path.join(ROOT, 'assets', 'rig', cid)
    with open(rig + '.png', 'rb') as f, open(rig + '.json') as j:
        data[cid]['rig'] = {'src': 'data:image/png;base64,' + base64.b64encode(f.read()).decode(), **json.load(j)}

block = ('// original anime-style pixel art, generated by tools/build_sprites.py\nconst DEFAULT_SPRITES = {\n'
         + ',\n'.join(f'  {k}:{json.dumps(v)}' for k, v in data.items()) + '\n};')
out = tpl.replace('/*DEFAULT_SPRITES*/', block, 1)
path = os.path.join(ROOT, 'ro-autobattler.html')
open(path, 'w', encoding='utf8', newline='\n').write(out)
print(f'built ro-autobattler.html with {len(data)} sprites ({len(out) // 1024} KB)')

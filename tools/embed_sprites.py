"""Embed assets/units/*.png into ro-autobattler.html as DEFAULT_SPRITES (re-runnable)."""
import base64, json, os, re
root = os.path.join(os.path.dirname(__file__), '..')
html_path = os.path.join(root, 'ro-autobattler.html')
html = open(html_path, encoding='utf-8').read()
ids = re.findall(r"\{id:'(\w+)'", html)
sprites = {}
for i in ids:
    with open(os.path.join(root, 'assets', 'units', i + '.png'), 'rb') as fh:
        sprites[i] = {'src': 'data:image/png;base64,' + base64.b64encode(fh.read()).decode(), 'faceLeft': True}
HEAD = '// DEFAULT_SPRITES: original pixel art generated by tools/make_sprites.py (all face left)\n'
TAIL = 'for(const [id,v] of Object.entries(DEFAULT_SPRITES)) setSprite(id,v.src,v.faceLeft);\n'
block = (HEAD + 'const DEFAULT_SPRITES = ' + json.dumps(sprites, separators=(',', ':')).replace('},"', '},\n  "') + ';\n' + TAIL)
# drop a previous block (exactly HEAD ... TAIL) before inserting the new one
if HEAD in html:
    a = html.index(HEAD); b = html.index(TAIL, a) + len(TAIL)
    html = html[:a] + html[b:]
anchor = "for(const [id,v] of Object.entries(readStore())) setSprite(id,v.src,v.faceLeft);"
assert anchor in html and 'function readStore' in html
html = html.replace(anchor, block + anchor)
open(html_path, 'w', encoding='utf-8', newline='\n').write(html)
print('embedded', len(sprites), 'sprites;', os.path.getsize(html_path), 'bytes')

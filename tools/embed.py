"""Embeds assets/units/*.png into ro-autobattler.html as DEFAULT_SPRITES.
Re-run after make_sprites.py; it replaces the block between the markers."""
import base64
import json
import os
import re

HERE = os.path.dirname(__file__)
HTML = os.path.join(HERE, '..', 'ro-autobattler.html')
UNITS = os.path.join(HERE, '..', 'assets', 'units')
FACE_LEFT = True  # every generated sprite looks down-left

ids = re.findall(r"\{id:'(\w+)'", open(HTML, encoding='utf8').read())
data = {}
for cid in ids:
    with open(os.path.join(UNITS, cid + '.png'), 'rb') as f:
        data[cid] = {'src': 'data:image/png;base64,' + base64.b64encode(f.read()).decode(), 'faceLeft': FACE_LEFT}

block = ('// DEFAULT_SPRITES:BEGIN (generated by tools/embed.py)\nconst DEFAULT_SPRITES = {\n'
         + ',\n'.join(f'  {k}:{json.dumps(v)}' for k, v in data.items())
         + '\n};\n// DEFAULT_SPRITES:END')

src = open(HTML, encoding='utf8').read()
if 'DEFAULT_SPRITES:BEGIN' in src:
    src = re.sub(r'// DEFAULT_SPRITES:BEGIN.*?// DEFAULT_SPRITES:END', lambda m: block, src, flags=re.S)
else:
    src = src.replace('const SPR = {};\n', 'const SPR = {};\n' + block + '\n', 1)
open(HTML, 'w', encoding='utf8', newline='\n').write(src)
print(f'embedded {len(data)} sprites, html size {len(src) // 1024} KB')
